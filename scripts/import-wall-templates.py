"""Import only Folia rectangle data from the deployed Peach 0.52.0 JS bundle."""
import json
from pathlib import Path
import re
import sys

source = Path(sys.argv[1]).read_text(encoding="utf-8-sig")
start = source.index("var eK = [", source.index("// src/react/video-wall/folia/blockReflows.ts")) + len("var eK = ")
end = source.index(", nK = ", start)
reflows, templates = source[start:end].split(", tK = ")
def parse(value):
    return json.loads(re.sub(r"\b(x|y|cols|rows):", r'"\1":', value))
def rect(value):
    return "WallCell(x: {x}, y: {y}, columns: {cols}, rows: {rows})".format(**value)
def array(values):
    return "[" + ", ".join(map(rect, values)) + "]"
result = "// Generated by scripts/import-wall-templates.py from Peach 0.52.0 Folia rectangle data.\nimport Foundation\n\nenum WallTemplates {\n    static let base: [[WallCell]] = [\n"
result += ",\n".join("        " + array(v) for v in parse(templates))
result += "\n    ]\n    static let focused: [[[WallCell]]] = [\n"
result += ",\n".join("        [\n" + ",\n".join("            " + array(v) for v in group) + "\n        ]" for group in parse(reflows))
result += "\n    ]\n}\n"
Path("PeachTest/Core/WallTemplates.swift").write_text(result, encoding="utf-8")
